export function translate(language: string | undefined, key: TranslationKey): string {
  return (language === "vi" ? vi[key] : undefined) ?? en[key];
}

export function formatTranslation(language: string | undefined, key: TranslationKey, values: Record<string, string | number>): string {
  return translate(language, key).replace(/\{([a-z]+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function photoCount(language: string | undefined, count: number): string {
  return formatTranslation(language, count === 1 ? "onePhoto" : "photosCount", { count });
}
